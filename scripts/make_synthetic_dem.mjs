// Generates SYNTHETIC elevation data for development when the real DEM cannot be
// downloaded. It is NOT a NASA measurement. dem.meta.json carries synthetic:true,
// and the application shows a persistent warning while it is loaded.
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "..", "public", "data");
mkdirSync(out, { recursive: true });

const rows = 500, cols = 500, d = 0.01, west = 74, north = 22;
let seed = 20261113;
const rnd = () => ((seed = (seed * 1664525 + 1013904223) >>> 0) / 2 ** 32);
const lattice = Array.from({ length: 64 * 64 }, rnd);
const sm = (t) => t * t * (3 - 2 * t);
function noise(x, y) {
  const xi = Math.floor(x), yi = Math.floor(y), xf = x - xi, yf = y - yi;
  const v = (i, j) => lattice[((j & 63) << 6) | (i & 63)];
  const a = v(xi, yi), b = v(xi + 1, yi), c = v(xi, yi + 1), e = v(xi + 1, yi + 1);
  const u = sm(xf), w = sm(yf);
  return a + (b - a) * u + (c - a) * w + (a - b - c + e) * u * w;
}
const fbm = (x, y) => { let s = 0, amp = 1, f = 1; for (let o = 0; o < 5; o++) { s += amp * noise(x * f, y * f); amp *= 0.5; f *= 2; } return s; };

const z = new Float32Array(rows * cols);
for (let r = 0; r < rows; r++) for (let c = 0; c < cols; c++) {
  const lon = west + (c + 0.5) * d, lat = north - (r + 0.5) * d;
  let h = -2500 + 900 * fbm(c / 40, r / 40);
  // one circular bowl with a raised rim, one broad ridge
  const dc = Math.hypot(lon - 77.2, lat - 19.6);
  h -= 1200 * Math.exp(-((dc / 0.45) ** 2));
  h += 700 * Math.exp(-(((dc - 0.55) / 0.12) ** 2));
  h += 1500 * Math.exp(-((((lon - 75.4) * 0.8 + (lat - 20.0) * 0.6) / 0.25) ** 2));
  z[r * cols + c] = h;
}
// Two data gaps so missing-data handling is exercised.
for (let r = 120; r < 170; r++) for (let c = 300; c < 370; c++) z[r * cols + c] = NaN;
for (let r = 330; r < 350; r++) for (let c = 60; c < 140; c++) z[r * cols + c] = NaN;

writeFileSync(join(out, "dem.bin"), Buffer.from(z.buffer));
writeFileSync(join(out, "dem.meta.json"), JSON.stringify({
  id: "synthetic-dev-dem",
  title: "SYNTHETIC development terrain (not NASA data)",
  synthetic: true,
  source: "Generated by scripts/make_synthetic_dem.mjs (seeded value noise plus a bowl and a ridge). Not a measurement.",
  sourceUrl: "",
  radiusM: 3396190,
  rows, cols, west, north, dLon: d, dLat: d,
  elevationUnit: "m",
  processing: ["Procedurally generated; no NASA data used.", "Two rectangular gaps set to missing to exercise unknown-data handling."],
  limitations: ["Elevations, slopes and routes derived from this grid say nothing about the real surface of Mars.", "Replace with `npm run data:real` output before any scientific use."],
}, null, 2));
console.log(`wrote ${rows}x${cols} synthetic grid`);
